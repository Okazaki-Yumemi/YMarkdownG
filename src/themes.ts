export function getTheme(id: string) {
  return themes.find((t) => t.id === id) || themes[id === "light" ? 2 : 0];
}
export function themeVariables(id: string) {
  const t = getTheme(id);
  return {
    "--base": t.bg,
    "--paper": t.bg,
    "--canvas": t.bg,
    "--sidebar": t.sidebar,
    "--panel": t.panel,
    "--text": t.text,
    "--muted": t.muted,
    "--border": t.border,
    "--hover": t.panel,
    "--syntax-keyword": t.keyword,
    "--syntax-string": t.string,
    "--syntax-number": t.number,
    "--syntax-comment": t.comment,
    "--syntax-type": t.type,
    "--syntax-red": t.red,
  };
}
export function sourceTheme(id: string) {
  const t = getTheme(id);
  return [
    EditorView.theme(
      {
        "&": { color: t.text, backgroundColor: "transparent" },
        ".cm-content": { caretColor: t.accent },
        ".cm-cursor": { borderLeftColor: t.accent },
      },
      { dark: t.dark },
    ),
    syntaxHighlighting(
      HighlightStyle.define([
        { tag: tags.keyword, color: t.keyword },
        { tag: [tags.string, tags.regexp], color: t.string },
        { tag: [tags.number, tags.bool, tags.null], color: t.number },
        { tag: [tags.comment, tags.meta], color: t.comment },
        { tag: [tags.typeName, tags.className], color: t.type },
        { tag: [tags.function(tags.variableName)], color: t.accent },
        { tag: tags.heading, color: t.red, fontWeight: "600" },
        { tag: tags.strong, fontWeight: "bold" },
        { tag: tags.emphasis, fontStyle: "italic" },
        { tag: tags.link, color: t.accent, textDecoration: "underline" },
      ]),
    ),
  ];
}
